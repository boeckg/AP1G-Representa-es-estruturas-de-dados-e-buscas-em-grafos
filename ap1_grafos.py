def bfs(grafo, origem):
    visitado = {}
    distancia = {}
    antecessor = {}
    ordem = []
    for v in grafo:
        visitado[v] = False
        distancia[v] = -1
        antecessor[v] = None
    visitado[origem] = True
    distancia[origem] = 0
    fila = []
    fila.append(origem)
    while len(fila) > 0:
        u = fila[0]
        fila = fila[1:]
        ordem.append(u)
        for v in vizinhos(grafo, u):
            if visitado[v] == False:
                visitado[v] = True
                distancia[v] = distancia[u] + 1
                antecessor[v] = u
                fila.append(v)
    return ordem, distancia, antecessor

