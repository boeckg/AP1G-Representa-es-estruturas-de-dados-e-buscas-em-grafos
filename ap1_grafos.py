def estacoes_2_conexoes_lista(lista_adj, origem):
    nivel_1 = lista_adj[origem]
    nivel_2 = []
    for vertice in nivel_1:
        for vizinho in lista_adj[vertice]:
            if vizinho != origem and vizinho not in nivel_1 and vizinho not in nivel_2:
                nivel_2.append(vizinho)
    resultado = nivel_1 + nivel_2
    return resultado

def estacoes_2_conexoes_matriz(matriz, vertices, origem):
    i_origem = vertices.index(origem)
    nivel_1 = []
    for j in range(len(vertices)):
        if matriz[i_origem][j] == 1:
            nivel_1.append(vertices[j])
    nivel_2 = []
    for vertice in nivel_1:
        i = vertices.index(vertice)
        for j in range(len(vertices)):
            if matriz[i][j] == 1:
                vizinho = vertices[j]
                if vizinho != origem and vizinho not in nivel_1 and vizinho not in nivel_2:
                    nivel_2.append(vizinho)

    resultado = nivel_1 + nivel_2
    return resultado

def estacoes_2_conexoes_arestas(arestas, origem):
    nivel_1 = []
    for u, v in arestas:
        if u == origem:
            nivel_1.append(v)
        elif v == origem:
            nivel_1.append(u)
    nivel_2 = []
    for vertice in nivel_1:
        for u, v in arestas:
            if u == vertice and v != origem and v not in nivel_1 and v not in nivel_2:
                nivel_2.append(v)
            elif v == vertice and u != origem and u not in nivel_1 and u not in nivel_2:
                nivel_2.append(u)

    resultado = nivel_1 + nivel_2
    return resultado


